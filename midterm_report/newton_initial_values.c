#include <stdio.h>
#include <math.h>

/*
 * 解くべき方程式: f(t) = t*sin(t) + 3*cos(t) = 0
 * この関数は複数の実数解を持つ。ニュートン法は初期値によって
 * 異なる解へ収束するため、複数の初期値から探索する。
 */
double f(double t)  { return t * sin(t) + 3.0 * cos(t); }   /* f(t)=t sin t + 3 cos t */

/*
 * f(t) の導関数: f'(t) = sin(t) + t*cos(t) - 3*sin(t) = t*cos(t) - 2*sin(t)
 * ニュートン法の更新式 t_{n+1} = t_n - f(t_n)/f'(t_n) に必要。
 * f'(t) = 0 となる点（極値）付近では収束しない・発散する可能性がある。
 */
double df(double t) { return t * cos(t) - 2.0 * sin(t); }   /* f'(t)=t cos t - 2 sin t */

int main(void) {
    /* 0~2π を 0.5 刻みで並べた初期値リスト（必要に応じて値を追加・変更） */
    /* 異なる初期値から出発することで、方程式が持つ複数の解を網羅的に探索する */
    double t0_list[] = {0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0,
                        3.5, 4.0, 4.5, 5.0, 5.5, 6.0, 6.2832};
    int    m = sizeof(t0_list) / sizeof(t0_list[0]);  /* 初期値の個数 */

    double eps = 1.0e-12;    /* 収束判定のしきい値: |t_{n+1} - t_n| < eps で収束とみなす */
    int    max_iter = 200;   /* 発散を防ぐための反復上限回数 */

    /* 表のヘッダを出力 */
    printf("   t0          解 t          反復n\n");
    printf("----------------------------------------\n");

    /* ---- 各初期値についてニュートン法を実行 ---- */
    for (int k = 0; k < m; k++) {
        double t = t0_list[k];  /* 現在の近似値（初期値で初期化） */
        double tn;              /* 更新後の近似値 t_{n+1} */
        int n, conv = 0;        /* n: 反復カウンタ, conv: 収束フラグ（0=未収束, 1=収束） */

        /* ---- ニュートン法の反復ループ ---- */
        for (n = 0; n < max_iter; n++) {
            tn = t - f(t) / df(t);  /* ニュートン法の更新式: t_{n+1} = t_n - f(t_n)/f'(t_n) */

            /* 収束判定: 前の値との差の絶対値が eps より小さければ収束 */
            if (fabs(tn - t) < eps) {
                t = tn;   /* 収束した値を保存 */
                conv = 1; /* 収束フラグを立てる */
                break;
            }

            t = tn; /* 次の反復に備えて近似値を更新 */

            /* 発散検出: |t| が 10^6 を超えたら無限発散とみなして打ち切り */
            if (fabs(t) > 1.0e6) break;
        }

        /* ---- 結果の出力 ---- */
        if (conv)
            /* 収束した場合: 初期値・解・収束までの反復回数を表示 */
            printf("%6.2f  %14.8f   %3d\n", t0_list[k], t, n + 1);
        else
            /* 収束しなかった場合（発散・上限到達）: その旨を表示 */
            printf("%6.2f      （発散・収束せず）\n", t0_list[k]);
    }
    return 0;
}
