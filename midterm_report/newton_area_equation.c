#include <stdio.h>
#include <math.h>

/*
 * 解くべき方程式: f(t) = t*sin(t) + 3*cos(t) = 0
 * この超越方程式は解析的に解けないため、ニュートン法（逐次近似）で数値解を求める。
 * 解は無数に存在し、どの解へ収束するかは初期値に依存する。
 */
double f(double t) {
    return t * sin(t) + 3.0 * cos(t);
}

/*
 * f(t) の導関数: f'(t) = t*cos(t) - 2*sin(t)
 * 積の微分則より:
 *   d/dt [t*sin(t)] = sin(t) + t*cos(t)
 *   d/dt [3*cos(t)] = -3*sin(t)
 *   → f'(t) = sin(t) + t*cos(t) - 3*sin(t) = t*cos(t) - 2*sin(t)
 *
 * ニュートン法の更新式: t_{n+1} = t_n - f(t_n)/f'(t_n)
 * f'(t) ≈ 0 の点（関数の極値付近）では除算が不安定になり発散しやすい。
 */
double df(double t) {
    return t * cos(t) - 2.0 * sin(t);
}

int main(void) {
    double t;                /* 現在の近似値（最初は初期値 t_0 として使用） */
    double tn;               /* ニュートン法で更新した次の近似値 t_{n+1} */
    double eps = 1.0e-12;    /* 収束判定のしきい値: |t_{n+1} - t_n| < eps で収束とみなす */
    int n, max_iter = 100;   /* n: 反復カウンタ, max_iter: 発散防止のための反復上限 */

    /* 初期値をキーボードから入力（どの解へ収束するかは初期値で決まる） */
    printf("初期値 t0 を入力: ");
    scanf("%lf", &t);   /* %lf で double 型として読み込む */

    /* 反復過程の表ヘッダを出力 */
    printf(" n            t_n                f(t_n)\n");
    printf("------------------------------------------\n");

    /* ---- ニュートン法の反復ループ ---- */
    for (n = 0; n < max_iter; n++) {

        /* ニュートン法の更新式: t_{n+1} = t_n - f(t_n)/f'(t_n) */
        /* 接線と x 軸の交点を次の近似値とすることで、急速に真の解へ近づく（2 次収束） */
        tn = t - f(t) / df(t);

        /* 各反復の結果を出力: 反復番号・更新後の近似値・その点での残差 f(t_{n+1}) */
        /* f(t_n) → 0 に近づいていくことで収束の様子を視認できる */
        printf("%2d  %18.12f  %+.3e\n", n + 1, tn, f(tn));

        /* 収束判定: 前の値との差の絶対値が eps を下回ったら解が定まったとみなす */
        /* fabs() で符号を無視して差の大きさだけを比較する */
        if (fabs(tn - t) < eps) {
            t = tn;  /* 収束した値を t に保存してループを抜ける */
            break;
        }

        t = tn;   /* 次の反復に備えて近似値を更新（t_n ← t_{n+1}） */
    }
    /* max_iter 回に達しても収束しなかった場合はそのまま終了（発散の可能性あり） */

    /* ---- 最終結果の出力 ---- */
    printf("------------------------------------------\n");
    printf("解       t = %.12f\n", t);            /* 収束した解 t* を12 桁で表示 */
    printf("検算  f(t) = %.3e\n", f(t));          /* f(t*) ≈ 0 であることを確認 */
    /* 係数 a = sin(t)/t^2 は、この問題の物理的・数学的文脈での派生量 */
    printf("係数     a = sin(t)/t^2 = %.12f\n", sin(t) / (t * t));

    return 0;
}
